import { defineRouteMiddleware } from '@astrojs/starlight/route-data';
import type { SidebarEntry } from '@astrojs/starlight/route-data';
import { getCollection } from 'astro:content';
import { stripBase, withBase } from './lib/base';
import { extractHowTos } from './lib/howto.mjs';

/**
 * Two left navs out of one sidebar config.
 *
 * The API reference is its own destination, reached from the top-of-rail
 * "API Reference" row. On /api/ pages the left nav shows ONLY the
 * endpoint groups, and on every other page it shows everything EXCEPT them.
 * The alternative -- separate `sidebar` arrays -- is impossible (Starlight
 * takes exactly one) and would duplicate entries that already exist in the
 * sidebar data files, letting the copies drift.
 *
 * Starlight builds the sidebar before rendering and exposes it on the route,
 * so the split happens here rather than in Sidebar.astro, which hands the
 * tree straight to Starlight's own renderer.
 *
 * Arcus rides in the same array as a wrapper group ("Arcus"), unwrapped on
 * /arcus/ pages and dropped on every other page -- so the reader only ever
 * sees one product's sections.
 */

/**
 * Each product's API reference: the URL prefix its endpoint pages live under,
 * and the label of the group holding them in that product's tree. Both get the
 * same treatment; only these strings differ.
 */
const API_SECTIONS = [
	{ path: '/api/', group: 'REST APIs' },
	{ path: '/arcus/api-reference/', group: 'API Reference' },
] as const;

/** Each product's changelog page, and the release feed it draws from. */
const CHANGELOGS = [
	{ path: '/changelog', product: 'suite' },
	{ path: '/arcus/changelog', product: 'arcus' },
] as const;

/** The Arcus tree: its URL prefix and the wrapper group holding it. */
const ARCUS_SECTION = { path: '/arcus/', group: 'Arcus' } as const;

/** Pages served by the Arcus tree. ProductSwitcher.astro reads this too, so
 *  the button's label and the rail can never disagree about the product. */
export const isArcusPath = (pathname: string) =>
	stripBase(pathname).startsWith(ARCUS_SECTION.path);

/** Pages served by the API-only nav, in EITHER product. Sidebar.astro keys the
 *  API-nav treatment off this too, so a Testsigma-only test here would have left
 *  Arcus endpoint pages rendering as ordinary rows.
 *  stripBase: pathnames carry the /docs-new base in every environment that sets one. */
export const isApiReferencePath = (pathname: string) =>
	API_SECTIONS.some((s) => stripBase(pathname).startsWith(s.path));

/** The group label of the API reference serving this path ("REST APIs" for
 *  Testsigma, "API Reference" for Arcus). Breadcrumbs.astro puts it back as the
 *  root crumb, which a hardcoded label got wrong on the other product. */
export const apiSectionLabel = (pathname: string) =>
	API_SECTIONS.find((s) => stripBase(pathname).startsWith(s.path))?.group;

type Group = Extract<SidebarEntry, { type: 'group' }>;

const isGroup = (entry: SidebarEntry): entry is Group => entry.type === 'group';

// ── autogenerated group labels ──
// Starlight labels an autogenerated group with the raw folder name
// ("test-authoring"). Top-level sections get their label from the sidebar
// config, so only NESTED folders need fixing: dashes become spaces and words
// title-case, with an exception map for names the rule can't produce. Config
// labels already contain an uppercase letter, so they never match the
// all-lowercase test and are left alone.
const LABEL_EXCEPTIONS: Record<string, string> = {
	'ci-cd': 'CI/CD',
	ios: 'iOS',
	'rest-apis': 'REST APIs',
};

const prettifyLabel = (label: string) =>
	LABEL_EXCEPTIONS[label] ??
	label.replace(/-/g, ' ').replace(/\b[a-z]/g, (c) => c.toUpperCase());

const prettifyGroups = (entries: SidebarEntry[]): SidebarEntry[] =>
	entries.map((entry) =>
		isGroup(entry)
			? {
					...entry,
					label: entry.label === entry.label.toLowerCase() ? prettifyLabel(entry.label) : entry.label,
					entries: prettifyGroups(entry.entries),
				}
			: entry
	);

export const onRequest = defineRouteMiddleware(async (context) => {
	const { starlightRoute } = context.locals;
	// Base-free, so it can be matched against the literal prefixes below.
	const pathname = stripBase(context.url.pathname);

	// ── 0. pick the product tree ──
	// Each product carries its OWN utility rows, so this runs before they are
	// read below: borrowing Testsigma's would point Arcus's rail at Testsigma's API
	// reference and Testsigma's changelog.
	const arcusGroup = starlightRoute.sidebar.find(
		(e): e is Group => isGroup(e) && e.label === ARCUS_SECTION.group
	);
	if (arcusGroup) {
		starlightRoute.sidebar = pathname.startsWith(ARCUS_SECTION.path)
			? arcusGroup.entries
			: starlightRoute.sidebar.filter((e) => e !== arcusGroup);
	}

	// The top-of-rail utility rows (Home / API Reference / Changelog) appear on
	// EVERY tree, including the swapped-in API and changelog navs below.
	const utilityRows = starlightRoute.sidebar.filter(
		(e) => e.type === 'link' && e.attrs?.['data-nav-utility'] !== undefined
	);

	// ── 1. split the API reference out ──
	// The loop covers both products, but only the one whose group survived
	// step 0 is ever found, so the other iteration is a no-op.
	for (const section of API_SECTIONS) {
		const apiGroup = starlightRoute.sidebar.find(
			(e): e is Group => isGroup(e) && e.label === section.group
		);
		if (!apiGroup) continue;
		starlightRoute.sidebar = pathname.startsWith(section.path)
			? // Unwrap the group so each entity (Projects, Test Cases, ...) becomes a
				// top-level section, keeping the utility rows above them.
				[...utilityRows, ...apiGroup.entries]
			: starlightRoute.sidebar.filter((e) => e !== apiGroup);
	}

	// ── 1b. changelog nav: utility rows + one link per release ──
	// The page renders every release as a card (ChangelogFeed.astro); the rail
	// mirrors it as anchors, newest first, using the same id the feed stamps on
	// each headline. Filtered by product for the same reason the feed is.
	const changelog = CHANGELOGS.find((c) => pathname.startsWith(c.path));
	if (changelog) {
		const releases = (await getCollection('changelog'))
			.filter((r) => r.data.product === changelog.product)
			.sort((a, b) => new Date(b.data.date).getTime() - new Date(a.data.date).getTime());
		starlightRoute.sidebar = [
			...utilityRows,
			{
				type: 'group',
				label: 'Releases',
				collapsed: false,
				badge: undefined,
				entries: releases.map((r, i) => ({
					type: 'link',
					// Releases are identified by date, not version: only a handful
					// ever had a vX.Y.Z. The entry id is the filename, which is the
					// anchor the feed stamps on each headline.
					label: r.data.date,
					href: `${context.url.pathname}#${r.id}`,
					isCurrent: false,
					// The newest release wears a chip, computed from the sort rather
					// than a frontmatter flag -- a flag goes stale the moment a new
					// release file is added. The headline is the row's tooltip.
					badge: i === 0 ? { text: 'Latest', variant: 'success' } : undefined,
					attrs: {
						'data-release': '',
						title: r.data.headline,
					},
				})),
			},
		];
	}

	// ── 2. top-level sections start open, nested groups stay closed ──
	// The reader sees every section and its own pages on arrival, so the shape
	// of the product is visible without clicking; sub-folders stay shut so a
	// section is a readable list rather than a wall. Deliberately NOT recursive
	// -- the nested groups keep the `collapsed` flags the sidebar data authors.
	//
	// Starlight still opens the ancestor chain of the current page on top of
	// this, and persists whatever the reader opens or closes from there, so
	// this only sets the state a first visit lands on.
	//
	// The API reference nav is unaffected by the shallowness: its entity groups
	// (Projects, Test Cases, ...) ARE the top level once the middleware unwraps
	// that section above, so they all open.
	starlightRoute.sidebar = starlightRoute.sidebar.map((entry) =>
		isGroup(entry) ? { ...entry, collapsed: false } : entry
	);

	// ── 3. prettify autogenerated folder labels ──
	starlightRoute.sidebar = prettifyGroups(starlightRoute.sidebar);

	// ── 4. schema.org JSON-LD ──
	// One TechArticle per page so search engines read the title, owner and
	// date without guessing, plus one HowTo per <Steps> block, generated from
	// the steps themselves (src/lib/howto.mjs). dateModified only appears once
	// Starlight's `lastUpdated` is switched on. No BreadcrumbList: sidebar
	// groups have no URLs, and every crumb but the last needs one. Skipped on
	// the 404 page, which is not an article.
	const { entry, lastUpdated, headings } = starlightRoute;
	if (entry.id !== '404') {
		// ── 4a. product in the <title> ──
		// Testsigma and Arcus share page names ("Overview", "Azure DevOps"), and the
		// default "<page> | Testsigma" made 16 titles collide across products. A
		// page that already names its product (the homes) keeps the short form.
		const product = isArcusPath(context.url.pathname)
			? { word: 'Arcus', suffix: 'Arcus by Testsigma' }
			: { word: 'Testsigma', suffix: 'Testsigma' };
		const titleTag = starlightRoute.head.find((t) => t.tag === 'title');
		if (titleTag) {
			const suffix = entry.data.title.includes(product.word) ? 'Testsigma' : product.suffix;
			// A title that already says Testsigma ("Testsigma Docs", "Testsigma
			// REST API") needs no suffix at all.
			titleTag.content = entry.data.title.includes('Testsigma')
				? entry.data.title
				: `${entry.data.title} | ${suffix}`;
		}

		const pageUrl = new URL(context.url.pathname, context.site).href;
		const howTos = extractHowTos(entry.body ?? '').map(({ name, steps }) => {
			// The rendered heading has curly quotes where the source has straight.
			const slug = headings.find((h) => h.text.replace(/[‘’]/g, "'").replace(/[“”]/g, '"') === name)?.slug;
			return {
				'@type': 'HowTo',
				name: name ?? entry.data.title,
				...(slug && { url: `${pageUrl}#${slug}` }),
				step: steps.map((text, i) => ({ '@type': 'HowToStep', position: i + 1, text })),
			};
		});
		starlightRoute.head.push({
			tag: 'script',
			attrs: { type: 'application/ld+json' },
			content: JSON.stringify({
				'@context': 'https://schema.org',
				'@graph': [
					{
						'@type': 'TechArticle',
						headline: entry.data.title,
						description: entry.data.description,
						url: pageUrl,
						...(lastUpdated && { dateModified: lastUpdated.toISOString() }),
						publisher: {
							'@type': 'Organization',
							name: 'Testsigma',
							url: 'https://testsigma.com',
							logo: new URL(withBase('/testsigma-mark.svg'), context.site).href,
						},
					},
					...howTos,
				],
			}),
		});
	}
});
